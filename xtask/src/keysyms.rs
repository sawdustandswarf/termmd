//! Keysym tables from `data/xkbcommon-keysyms.h`.
//!
//! Emits name<->value tables, a keysym->Unicode table for legacy keysyms (those
//! outside the identity and 0x01000000+ ranges) and named constants.

use std::collections::BTreeMap;
use std::fmt::Write as _;

pub struct Keysym {
    pub name: String,
    pub value: u32,
    /// Direct Unicode mapping from the header comment (`U+XXXX` or `<U+XXXX>`).
    /// Deprecated `(U+XXXX)` mappings are ignored, as xkbcommon does.
    pub unicode: Option<u32>,
    pub deprecated: bool,
}

pub fn parse(src: &str) -> Result<Vec<Keysym>, String> {
    let mut out = Vec::new();
    for (n, line) in src.lines().enumerate() {
        let Some(rest) = line.strip_prefix("#define XKB_KEY_") else { continue };
        let mut parts = rest.split_whitespace();
        let name = parts.next().ok_or(format!("line {}: missing name", n + 1))?;
        let raw = parts.next().ok_or(format!("line {}: missing value", n + 1))?;
        let value = u32::from_str_radix(raw.trim_start_matches("0x"), 16)
            .map_err(|_| format!("line {}: bad value `{raw}`", n + 1))?;
        let comment = line.split_once("/*").map_or("", |(_, c)| c);
        let unicode = ["/* U+", "/*<U+"].iter().find_map(|p| line.split_once(p).map(|(_, r)| r)).and_then(|r| {
            u32::from_str_radix(&r[..r.find(|c: char| !c.is_ascii_hexdigit()).unwrap_or(r.len())], 16).ok()
        });
        out.push(Keysym { name: name.to_owned(), value, unicode, deprecated: comment.contains("deprecated") });
    }
    if out.is_empty() {
        return Err("no keysyms found".into());
    }
    Ok(out)
}

/// Keysyms whose Unicode value xkbcommon computes arithmetically.
fn is_direct(ks: u32) -> bool {
    matches!(ks, 0x20..=0x7e | 0xa0..=0xff | 0x0100_0100..=0x0110_ffff)
}

pub fn generate(keysyms: &[Keysym]) -> String {
    let mut s = String::from(
        "// @generated by `cargo xtask gen-keysyms` from data/xkbcommon-keysyms.h. Do not edit.\n\n\
         use super::keysym::Keysym;\n\n",
    );

    let mut by_name: Vec<&Keysym> = keysyms.iter().collect();
    by_name.sort_by(|a, b| a.name.as_bytes().cmp(b.name.as_bytes()));
    s.push_str("/// `(name, keysym)` sorted by name bytes, for binary search.\npub(super) static BY_NAME: &[(&str, u32)] = &[\n");
    for k in &by_name {
        let _ = writeln!(s, "    ({:?}, {:#x}),", k.name, k.value);
    }
    s.push_str("];\n\n");

    // Canonical name per value: the first non-deprecated definition in header order.
    let mut canonical: BTreeMap<u32, &str> = BTreeMap::new();
    for k in keysyms.iter().filter(|k| !k.deprecated) {
        canonical.entry(k.value).or_insert(&k.name);
    }
    for k in keysyms {
        canonical.entry(k.value).or_insert(&k.name);
    }
    s.push_str("/// `(keysym, canonical name)` sorted by keysym.\npub(super) static BY_VALUE: &[(u32, &str)] = &[\n");
    for (v, n) in &canonical {
        let _ = writeln!(s, "    ({v:#x}, {n:?}),");
    }
    s.push_str("];\n\n");

    let mut uni: BTreeMap<u32, u32> = BTreeMap::new();
    for k in keysyms {
        if let Some(u) = k.unicode
            && !is_direct(k.value)
        {
            uni.entry(k.value).or_insert(u);
        }
    }
    s.push_str(
        "/// `(keysym, Unicode scalar)` for keysyms outside the arithmetic ranges, sorted by keysym.\npub(super) static TO_UNICODE: &[(u32, u32)] = &[\n",
    );
    for (k, u) in &uni {
        let _ = writeln!(s, "    ({k:#x}, {u:#x}),");
    }
    s.push_str("];\n\n");

    s.push_str("#[allow(non_upper_case_globals)]\nimpl Keysym {\n");
    for k in keysyms {
        if k.name.starts_with(|c: char| c.is_ascii_digit()) {
            continue;
        }
        let _ = writeln!(s, "    pub const {}: Keysym = Keysym({:#x});", k.name, k.value);
    }
    s.push_str("}\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_values_and_unicode_comments() {
        let src = "\
#define XKB_KEY_BackSpace                     0xff08  /* U+0008 BACKSPACE */
#define XKB_KEY_KP_1                          0xffb1  /*<U+0031 DIGIT ONE>*/
#define XKB_KEY_Page_Up                       0xff55  /* deprecated alias for Prior */
#define XKB_KEY_Aogonek                       0x01a1  /* U+0104 LATIN CAPITAL LETTER A WITH OGONEK */
#define XKB_KEY_ohm                           0x7d9  /*(U+2126 OHM SIGN)*/
";
        let k = parse(src).unwrap();
        assert_eq!((k[0].value, k[0].unicode), (0xff08, Some(0x08)));
        assert_eq!(k[1].unicode, Some(0x31));
        assert!(k[2].deprecated && k[2].unicode.is_none());
        assert_eq!(k[3].unicode, Some(0x104));
        assert_eq!(k[4].unicode, None);
    }
}
