#!/usr/bin/env python3
"""Generate XKB test fixtures from the reference implementation (libxkbcommon).

For each layout below this compiles a keymap from RMLVO names, serializes it
exactly as a compositor sends it to clients, and records libxkbcommon's answer
for every keycode x group x modifier combination. termmd's own XKB code is
tested against these files; libxkbcommon is never linked into termmd.

Usage: python3 -I data/xkb/gen_reference.py   (writes into data/xkb/)
"""

import ctypes as C
import itertools
import os
import sys

xkb = C.CDLL("libxkbcommon.so.0")
xkb.xkb_context_new.restype = C.c_void_p
xkb.xkb_keymap_new_from_names.restype = C.c_void_p
xkb.xkb_keymap_new_from_names.argtypes = [C.c_void_p, C.c_void_p, C.c_int]
xkb.xkb_keymap_get_as_string.restype = C.c_void_p
xkb.xkb_keymap_get_as_string.argtypes = [C.c_void_p, C.c_int]
xkb.xkb_keymap_new_from_string.restype = C.c_void_p
xkb.xkb_keymap_new_from_string.argtypes = [C.c_void_p, C.c_char_p, C.c_int, C.c_int]
xkb.xkb_keymap_min_keycode.argtypes = [C.c_void_p]
xkb.xkb_keymap_max_keycode.argtypes = [C.c_void_p]
xkb.xkb_keymap_num_layouts_for_key.argtypes = [C.c_void_p, C.c_uint32]
xkb.xkb_keymap_key_repeats.argtypes = [C.c_void_p, C.c_uint32]
xkb.xkb_state_new.restype = C.c_void_p
xkb.xkb_state_new.argtypes = [C.c_void_p]
xkb.xkb_state_update_mask.argtypes = [C.c_void_p] + [C.c_uint32] * 6
xkb.xkb_state_key_get_syms.argtypes = [C.c_void_p, C.c_uint32, C.POINTER(C.POINTER(C.c_uint32))]
xkb.xkb_state_key_get_level.argtypes = [C.c_void_p, C.c_uint32, C.c_uint32]
xkb.xkb_state_key_get_layout.argtypes = [C.c_void_p, C.c_uint32]
xkb.xkb_state_key_get_consumed_mods2.restype = C.c_uint32
xkb.xkb_state_key_get_consumed_mods2.argtypes = [C.c_void_p, C.c_uint32, C.c_int]
libc = C.CDLL(None)
libc.free.argtypes = [C.c_void_p]


class RuleNames(C.Structure):
    _fields_ = [(n, C.c_char_p) for n in ("rules", "model", "layout", "variant", "options")]


LAYOUTS = [
    # (fixture name, layout, variant, options)
    ("us-omarchy", "us", "", "compose:caps,shift:both_capslock_cancel"),
    ("de", "de", "", ""),
    ("fr", "fr", "", ""),
    ("gb-altgr", "gb", "extd", "lv3:ralt_switch"),
    ("us-ru", "us,ru", ",", "grp:alt_shift_toggle"),
]

# Real-modifier bits: Shift Lock Control Mod1 Mod2 Mod3 Mod4 Mod5
SHIFT, LOCK, CONTROL, MOD1, MOD2, MOD4, MOD5 = 1, 2, 4, 8, 16, 64, 128
BASE = [0, SHIFT, LOCK, SHIFT | LOCK, CONTROL, MOD1, CONTROL | MOD1, MOD4, MOD5, MOD5 | SHIFT, MOD2, MOD2 | SHIFT]

XKB_CONSUMED_MODE_XKB = 0


def main():
    out_dir = os.path.dirname(os.path.abspath(__file__))
    ctx = xkb.xkb_context_new(0)
    for name, layout, variant, options in LAYOUTS:
        names = RuleNames(b"evdev", b"pc105", layout.encode(), variant.encode(), options.encode())
        km0 = xkb.xkb_keymap_new_from_names(ctx, C.byref(names), 0)
        if not km0:
            sys.exit(f"{name}: failed to compile")
        text_p = xkb.xkb_keymap_get_as_string(km0, 1)  # XKB_KEYMAP_FORMAT_TEXT_V1
        text = C.string_at(text_p)
        libc.free(text_p)
        # Re-load from the serialized text, as a client would.
        km = xkb.xkb_keymap_new_from_string(ctx, text, 1, 0)
        state = xkb.xkb_state_new(km)

        lines = []
        lo, hi = xkb.xkb_keymap_min_keycode(km), xkb.xkb_keymap_max_keycode(km)
        for kc in range(lo, hi + 1):
            layouts = xkb.xkb_keymap_num_layouts_for_key(km, kc)
            if layouts == 0:
                continue
            lines.append(f"R\t{kc}\t{int(bool(xkb.xkb_keymap_key_repeats(km, kc)))}")
            for group, mods in itertools.product(range(layouts), BASE):
                xkb.xkb_state_update_mask(state, mods, 0, 0, 0, 0, group)
                syms_p = C.POINTER(C.c_uint32)()
                n = xkb.xkb_state_key_get_syms(state, kc, C.byref(syms_p))
                syms = ",".join(f"{syms_p[i]:x}" for i in range(n))
                eff_layout = xkb.xkb_state_key_get_layout(state, kc)
                level = xkb.xkb_state_key_get_level(state, kc, eff_layout)
                consumed = xkb.xkb_state_key_get_consumed_mods2(state, kc, XKB_CONSUMED_MODE_XKB)
                lines.append(f"K\t{kc}\t{group}\t{mods}\t{level}\t{consumed}\t{syms}")

        with open(os.path.join(out_dir, f"{name}.xkb"), "wb") as f:
            f.write(text)
        with open(os.path.join(out_dir, f"{name}.ref"), "w") as f:
            f.write("# generated by gen_reference.py from libxkbcommon; do not edit\n")
            f.write("\n".join(lines) + "\n")
        print(f"{name}: {len(lines)} lines")


if __name__ == "__main__":
    main()
