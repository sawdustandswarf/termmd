/// The emoji named `name` (without colons).
pub fn lookup(name: &str) -> Option<&'static str> {
    CODES.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| CODES[i].1)
}

#[cfg(test)]
mod tests {
    #[test]
    fn sorted_and_found() {
        assert!(super::CODES.windows(2).all(|w| w[0].0 < w[1].0), "sorted, no duplicates");
        assert_eq!(super::lookup("joy"), Some("😂"));
        assert_eq!(super::lookup("+1"), Some("👍"));
        assert_eq!(super::lookup("nope"), None);
    }
}
